// Helper functions
export function getPostsByStatus(status: string) {
  return mockPosts.filter((post) => post.status === status);
}

export function getPostsByDateRange(startDate: Date, endDate: Date) {
  return mockPosts.filter((post) => {
    if (!post.scheduled_for && !post.published_at) return false;
    const postDate = new Date(post.scheduled_for || post.published_at || "");
    return postDate >= startDate && postDate <= endDate;
  });
}

export function getPostsByPlatform(platform: string) {
  return mockPosts.filter((post) => post.platforms.includes(platform as any));
}
